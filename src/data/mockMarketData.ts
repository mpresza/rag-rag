/**
 * Generate synthetic realistic candlestick data for any asset and timeframe
 */
export function generateCandles(basePrice: number, timeframe: string, count: number = 80): CandleData[] {
  const candles: CandleData[] = [];
  const now = Date.now();
  
  let stepMs = 5 * 60 * 1000; // 5 min for 1D
  if (timeframe === '5D') stepMs = 30 * 60 * 1000;
  if (timeframe === '1M') stepMs = 4 * 3600 * 1000;
  if (timeframe === '3M') stepMs = 12 * 3600 * 1000;
  if (timeframe === '6M') stepMs = 24 * 3600 * 1000;
  if (timeframe === '1Y') stepMs = 2 * 24 * 3600 * 1000;
  if (timeframe === 'ALL') stepMs = 7 * 24 * 3600 * 1000;

  // Volatility scale based on price
  const volatility = basePrice * 0.008;
  
  let currentClose = basePrice * 0.95; // start a bit lower so we end near current price
  
  for (let i = count - 1; i >= 0; i--) {
    const time = now - i * stepMs;
    const date = new Date(time);
    
    let timeLabel = '';
    if (timeframe === '1D' || timeframe === '5D') {
      timeLabel = date.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    } else {
      timeLabel = date.toLocaleDateString([], { month: 'short', day: 'numeric' });
    }

    const open = currentClose;
    // Slight upward bias towards the end
    const progress = (count - i) / count;
    const drift = (basePrice - open) * (progress * 0.15) + (Math.sin(i * 0.3) * volatility * 0.5);
    const noise = (Math.random() - 0.48) * volatility * 1.5;
    const close = Math.max(basePrice * 0.3, open + drift + noise);
    
    const high = Math.max(open, close) + Math.random() * volatility * 0.8;
    const low = Math.min(open, close) - Math.random() * volatility * 0.8;
    
    const volume = Math.floor(Math.random() * 50000 + 10000) * (Math.abs(close - open) / (volatility || 1) + 0.5);

    candles.push({
      time,
      timeLabel,
      open: Number(open.toFixed(basePrice < 2 ? 4 : 2)),
      high: Number(high.toFixed(basePrice < 2 ? 4 : 2)),
      low: Number(low.toFixed(basePrice < 2 ? 4 : 2)),
      close: Number(close.toFixed(basePrice < 2 ? 4 : 2)),
      volume: Math.round(volume)
    });

    currentClose = close;
  }

  // Ensure last candle closes exactly at current price
  if (candles.length > 0) {
    const last = candles[candles.length - 1];
    last.close = basePrice;
    last.high = Math.max(last.high, basePrice);
    last.low = Math.min(last.low, basePrice);
  }

  return candles;
}

/**
 * Generate Order Book Depth ladder for an asset
 */
export function generateOrderBook(currentPrice: number): OrderBook {
  const bids: OrderBook['bids'] = [];
  const asks: OrderBook['asks'] = [];
  const step = currentPrice * 0.0008;

  let cumBid = 0;
  for (let i = 1; i <= 8; i++) {
    const price = Number((currentPrice - i * step).toFixed(currentPrice < 2 ? 4 : 2));
    const size = Math.floor(Math.random() * 800 + 200);
    cumBid += size;
    bids.push({ price, size, total: cumBid });
  }

  let cumAsk = 0;
  for (let i = 1; i <= 8; i++) {
    const price = Number((currentPrice + i * step).toFixed(currentPrice < 2 ? 4 : 2));
    const size = Math.floor(Math.random() * 800 + 200);
    cumAsk += size;
    asks.push({ price, size, total: cumAsk });
  }

  const spread = Number((asks[0].price - bids[0].price).toFixed(currentPrice < 2 ? 4 : 2));
  const spreadPercent = Number(((spread / currentPrice) * 100).toFixed(3));

  return { bids, asks, spread, spreadPercent };
}
